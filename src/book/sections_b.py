def syl_table(rows, cols_fn, lead, title, sec, toc=None, note=""):
    tb = "".join(f'<div class="syl-row" dir="rtl"><span class="syl-l">{l}</span>' + "".join(f"<span>{c}</span>" for c in cols_fn(l)) + f'<em>{NAME.get(l, "")}</em></div>' for l in rows)
    return dict(body=f'''<h1 class="title sm">{title}</h1><p class="lead">{lead}</p>
<div class="syl-table" lang="ar">{tb}</div>{note}
<div class="tbl-foot"><div class="checks">Прочитал(-а): <span>☐ 1 раз</span><span>☐ 2 раза</span><span>☐ 3 раза</span></div></div>''', section=sec, toc=toc)

def choose_rows(items):
    return "".join(f'<div class="ch"><div class="ch-q">{q}</div><div class="ch-opts" dir="rtl">{"".join(f"<span lang=ar>{o}</span>" for o in opts)}</div></div>' for q, opts in items)

def match_rows(pairs, colors=("#F6E1D8", "#E4E9F4", "#F3EADF", "#F8EEDB")):
    rights = [a for _, a in pairs]
    random.seed(len(pairs) + len(rights[0]))
    sh = rights[:]
    while sh == rights:
        random.shuffle(sh)
    return '<div class="match">' + "".join(f'<div class="m-row"><div class="m-l" style="background:{colors[i % 4]}">{t}<i></i></div><div class="m-gap"></div><div class="m-r"><i></i><span lang="ar" dir="rtl">{a}</span></div></div>'
                                           for i, ((t, _), a) in enumerate(zip(pairs, sh))) + '</div>'

def pale_row(items, size=80, w=120):
    return '<div class="trace-row" dir="rtl">' + "".join(trace_svg(s, size, w, 130, base=90, y=90, pale=True) for s in items) + '</div>'

def qgrid(frags):
    return '<div class="qgrid">' + "".join(frags) + '</div>'

