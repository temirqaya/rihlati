def forms(letter, connects):
    if letter == "ا":
        return [("ا", "отдельно"), ("ـا", "в конце")]
    if not connects:
        return [(letter, "отдельно"), ("ـ" + letter, "в конце")]
    return [(letter, "отдельно"), (letter + "ـ", "в начале"), ("ـ" + letter + "ـ", "в середине"), ("ـ" + letter, "в конце")]

