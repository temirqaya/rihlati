def lesson_plan(book, smeta):
    """Уроки строятся по страницам книги ученика (номера страниц — из реальной сборки)."""
    def find(pred):
        for m in smeta:
            if pred(m):
                return m["num"]
        raise ValueError("нет страницы")
    def h1(t):
        return find(lambda m: t in m["h1"])
    def mk(k):
        return find(lambda m: m["mark"] == k)
    L = []
    L.append(("Знакомство: герои, хадисы, алфавит, солнечные и лунные буквы, карта", 2, mk("L1") - 1, "Знает, зачем учим Коран; видел весь алфавит"))
    starts = [mk(f"L{i}") for i in range(1, 29, 2)]
    for j, st in enumerate(starts):
        a, b = LETTERS[j*2], LETTERS[j*2+1]
        end = (starts[j+1] - 1) if j + 1 < len(starts) else h1("Алфавит с картинками") - 1
        L.append((f"Буквы {a[0]} — {a[2]} и {b[0]} — {b[2]}", st, end, "Узнаёт, называет, обводит; различает похожие"))
    L.append(("Повторение алфавита: картинки, домики, лишняя буква, поезд", h1("Алфавит с картинками"), h1("Пропись:") - 1, "Называет все 28 букв по порядку"))
    p1 = h1("Пропись:")
    L.append(("Прописи: буквы 1–16", p1, p1 + 3, "Пишет справа налево, ставит точки"))
    L.append(("Прописи: буквы 17–28, формы букв, игра «точки»", p1 + 4, h1("Буквы надевают") - 1, "Пишет формы букв"))
    hk = h1("Буквы надевают")
    L.append(("Огласовки: фатха, касра, дамма; таблица 1", hk, hk + 1, "Читает слоги коротко"))
    L.append(("Огласовки: таблица 2, игры, колесо огласовок", hk + 2, h1("Сукун — буква") - 1, "Читает слоги со всеми буквами"))
    sk = h1("Сукун — буква")
    L.append(("Сукун: объяснение и таблицы", sk, sk + 2, "Читает закрытые слоги"))
    L.append(("Сукун: игры; шадда и гунна", sk + 3, h1("Читаем с шаддой"), "Удваивает букву, гунна 2 счёта"))
    L.append(("Шадда: игры и повторение", h1("Играем с шаддой"), h1("Танвин — двойная") - 1, "Различает сукун и шадду"))
    L.append(("Танвин", h1("Танвин — двойная"), h1("Мадд — длинные") - 1, "Читает «ан, ин, ун»"))
    L.append(("Мадд: длинные звуки", h1("Мадд — длинные"), h1("Буквы в соединении (1/2)") - 1, "Тянет мадд ровно 2 счёта"))
    j1 = h1("Буквы в соединении (1/2)")
    L.append(("Соединение букв: формы, «ручки букв»", j1, h1("Шесть букв-одиночек") - 1, "Узнаёт буквы в любой форме"))
    L.append(("Буквы-одиночки, слова из слогов, первые слова", h1("Шесть букв-одиночек"), h1("Откуда выходят звуки") - 1, "Читает слова по слогам и целиком"))
    t0 = h1("Откуда выходят звуки")
    L.append(("Махаридж и сифаты", t0, t0 + 1, "Показывает места выхода звуков"))
    L.append(("Лям в «аль»; нун с сукуном и танвин — обзор", t0 + 2, t0 + 3, "Различает солнечные и лунные"))
    L.append(("Изхар и идгам", h1("Изхар"), h1("Идгам"), "Находит правило в примере"))
    L.append(("Икляб и ихфа", h1("Икляб"), h1("Ихфа"), "Читает с гунной"))
    L.append(("Мим с сукуном и калькаля", h1("Мим с сукуном"), h1("Калькаля"), "Читает калькалю с «эхом»"))
    L.append(("Правила мадда, остановка, повторение", h1("Правила мадда"), h1("Мы готовимся читать") - 1, "Знает счёт мадда, знаки остановки"))
    q0 = h1("Мы готовимся читать")
    L.append(("Адаб чтения, слова аль-Фатихи, сура аль-Фатиха", q0, q0 + 2, "Читает аль-Фатиху с учителем"))
    L.append(("Суры аль-Ихлас, аль-Каусар, аль-Фаляк", q0 + 3, q0 + 4, "Читает суры по книге"))
    L.append(("Суры ан-Нас и аль-Аср, план чтения", q0 + 5, q0 + 6, "Читает суры по книге"))
    f0 = h1("Итоговая проверка · часть 1")
    L.append(("Итоговая проверка, достижения, диплом", f0, smeta[-1]["num"], "Проходит проверку, получает диплом"))
    rows = [f'<div class="lp"><b>{i}</b><span>{t}</span><em>{a if a == b else f"{a}–{b}"}</em><i>{g}</i><u>☐</u></div>' for i, (t, a, b, g) in enumerate(L, 1)]
    head = '<div class="lp lph"><b>№</b><span>Тема урока</span><em>Стр. ученика</em><i>Цель урока</i><u>✓</u></div>'
    per = 13
    parts = [rows[i:i + per] for i in range(0, len(rows), per)]
    for k, part in enumerate(parts):
        book.add(f'''<h1 class="title sm">План уроков ({k+1}/{len(parts)})</h1>
<p class="lead">{len(L)} уроков по 25–30 минут. Если тема не усвоена — повторите урок: темп задаёт ребёнок, а не план.</p>
<div class="lptab">{head}{"".join(part)}</div>''', section=TSEC, toc=("План уроков", "خُطَّةُ الدُّرُوسِ") if k == 0 else None)

